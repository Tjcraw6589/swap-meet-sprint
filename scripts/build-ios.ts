// Builds the ios target and packs it into one self contained HTML file for
// the Expo app: the script is inlined, so the app needs no network and no
// file server. Writes ios-app/game/index.html and ios-app/game/html.ts.
// Run with: npm run build:ios

import { execSync } from 'node:child_process'
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs'
import { join } from 'node:path'

execSync('npx vite build --logLevel warn', { stdio: 'inherit', env: { ...process.env, TARGET: 'ios' } })

const dist = 'dist/ios'
let html = readFileSync(join(dist, 'index.html'), 'utf8')
const tag = html.match(/<script type="module" crossorigin src="\.\/assets\/([^"]+\.js)"><\/script>/)
if (!tag) throw new Error('no module script tag in the ios build')
const js = readFileSync(join(dist, 'assets', tag[1]), 'utf8').replace(/<\/script/gi, '<\\/script')
html = html.replace(tag[0], () => `<script type="module">\n${js}\n</script>`)
const left = readdirSync(join(dist, 'assets')).filter((f) => f !== tag[1])
if (left.length) throw new Error(`more assets than one script: ${left.join(', ')}`)
if (/\s(src|href)="\.?\/?assets\//.test(html)) throw new Error('the ios html still points at an asset file')
if (/https?:\/\//.test(html.replace(/https?:\/\/(www\.)?w3\.org[^"'\s]*/g, ''))) {
  console.warn('note: the ios html contains an http address; check nothing is loaded from the network')
}

mkdirSync('ios-app/game', { recursive: true })
writeFileSync('ios-app/game/index.html', html)
writeFileSync(
  'ios-app/game/html.ts',
  `// Generated by scripts/build-ios.ts. Do not edit; run npm run build:ios.\n// The whole game as one HTML page, shown offline in the app's web view.\nexport const GAME_HTML: string = ${JSON.stringify(html)}\n`,
)
console.log(`ios-app/game/index.html  ${(html.length / 1024).toFixed(1)} KB`)
